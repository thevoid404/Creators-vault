import { Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { createHash, randomUUID } from 'node:crypto';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, extname, join, posix, resolve, sep } from 'node:path';
import type { SaveFileInput, StorageProvider, StoredFile } from '../storage-provider.interface';

/**
 * Local-disk implementation of `StorageProvider`.
 *
 * This exists so development works with no cloud credentials. Files are laid out
 * as `{root}/{ownerId}/{yyyy}/{mm}/{uuid}{ext}` — sharded by owner and month so a
 * single directory never accumulates an unmanageable number of entries, and
 * scoped by owner so one user's objects are trivially separable.
 *
 * The generated URLs point at the static mount configured in `main.ts`. Keys
 * contain a v4 UUID, so they are unguessable; that is the same security model a
 * public S3 bucket with random keys has, and it keeps preview images loadable by
 * an `<img>` tag, which a bearer-token-protected route would not be.
 */
@Injectable()
export class LocalDiskStorageProvider implements StorageProvider {
  readonly driver = 'local';

  private readonly logger = new Logger(LocalDiskStorageProvider.name);
  private readonly root: string;
  private readonly baseUrl: string;

  /** Public path prefix the storage root is mounted under. Must match `main.ts`. */
  static readonly URL_PREFIX = '/files';

  constructor(config: ConfigService) {
    this.root = resolve(process.cwd(), config.get<string>('storage.localRoot', './storage'));
    this.baseUrl = (config.get<string>('apiBaseUrl') ?? '').replace(/\/+$/, '');
  }

  async save(input: SaveFileInput): Promise<StoredFile> {
    const now = new Date();
    const year = String(now.getUTCFullYear());
    const month = String(now.getUTCMonth() + 1).padStart(2, '0');

    // The extension is taken from the original name only; the name itself is
    // discarded, so a hostile filename cannot influence the path.
    const extension = extname(input.originalName)
      .slice(0, 16)
      .replace(/[^A-Za-z0-9.]/g, '');
    const key = posix.join(input.ownerId, year, month, `${randomUUID()}${extension}`);

    const absolute = this.toAbsolute(key);
    await mkdir(dirname(absolute), { recursive: true });
    await writeFile(absolute, input.buffer);

    return {
      key,
      url: this.getUrl(key),
      sizeBytes: input.buffer.byteLength,
      mimeType: input.mimeType,
      checksum: createHash('sha256').update(input.buffer).digest('hex'),
    };
  }

  async delete(key: string): Promise<void> {
    try {
      await rm(this.toAbsolute(key), { force: true });
    } catch (error) {
      // Deleting an object that is already gone is not a failure — callers use
      // this during cleanup paths that may run twice.
      this.logger.warn(`Could not delete ${key}: ${(error as Error).message}`);
    }
  }

  getUrl(key: string): string {
    return `${this.baseUrl}${LocalDiskStorageProvider.URL_PREFIX}/${key}`;
  }

  async exists(key: string): Promise<boolean> {
    try {
      await stat(this.toAbsolute(key));
      return true;
    } catch {
      return false;
    }
  }

  /**
   * Resolves a key inside the storage root and refuses anything that escapes it.
   * Keys are generated by `save()` and are never user input today, but this is
   * the one place a traversal could ever reach the filesystem.
   */
  private toAbsolute(key: string): string {
    const absolute = resolve(this.root, key);
    if (absolute !== this.root && !absolute.startsWith(this.root + sep)) {
      throw new Error(`Storage key escapes the storage root: ${key}`);
    }
    return join(absolute);
  }
}
